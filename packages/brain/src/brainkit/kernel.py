"""The kernel: standing context every session starts with, rendered per scope chain.

It carries the brain's identity, the action policy, the standing rules and core facts
(each standing note's `startup_text`, or its body when it has none), and the retrieval
contract that tells the model to call `get_task_context` first. `CLAUDE.md` and `AGENTS.md`
at the repository root are this text rendered for the owner. They are rewritten after every
governed change, and `get_task_context` includes the current kernel whenever the client's
fingerprint is stale, so a session never works from an outdated startup file for long.
"""
from __future__ import annotations

import os
import re

from . import util
from .model import MAX_CRITICAL
from .scopes import Scopes

BANNER = ("<!-- GENERATED by brainkit from {vault}. Do not edit: change the vault, then run "
          "`{cli} kernel`. kernel-fingerprint: {fingerprint} -->")
DISCLOSE = "- Disclose thin, stale, contradictory or missing evidence. Archived notes are history."
INDEX_TITLES = 5        # must-hold titles per domain line; the rest come with the brief
INDEX_HINTS = 5         # words per domain line that say when it comes up
MUST_HOLD_INTRO = (
    "Each domain below has notes that must hold for any task in it. When a task touches one, "
    "get its brief first (`get_task_context`): the brief opens with these notes, then the "
    "notes that matter for the task. If you work without a brief, open each listed note with "
    "`get_note` before you act. Every other area of this Brain is in its map (`topics.md`); "
    "its notes come with the brief when they matter, and `search_notes` finds the rest.")


def _one_line(text: str) -> str:
    return re.sub(r"\s+", " ", str(text or "")).strip()


def standing_notes(index, chain, partitions=()) -> list:
    notes = [n for n in index.notes.values()
             if n.standing and Scopes.admits(n.scope, n.partition, chain, partitions)]
    return sorted(notes, key=lambda n: (chain.index(n.scope) if n.scope in chain else 0, n.id))


def must_hold_notes(index, chain, partitions=()) -> list:
    """The must-holds this scope chain can see, in id order."""
    return sorted((n for n in index.notes.values()
                   if n.must_hold and Scopes.admits(n.scope, n.partition, chain, partitions)),
                  key=lambda n: n.id)


def critical_ids(notes) -> list[str]:
    """The critical must-holds shown in full, at most MAX_CRITICAL of them, in id order. A
    Brain that marks more shows the rest by title (and the health check says so)."""
    return [n.id for n in notes if n.critical][:MAX_CRITICAL]


def _domains(config, index, note) -> list[tuple[str, str]]:
    """(key, name) for each domain a must-hold covers: an area, a topic, a project, or
    every task."""
    out = []
    for target in note.applies_to:
        if target == "*":
            out.append(("*", "every task"))
        elif target in index.focuses:
            out.append((f"project:{target}", f"the project {index.focuses[target].title}"))
        else:
            area, _sep, topic = target.partition("/")
            out.append((target, f"{area} ({topic.replace('-', ' ')})" if topic else area))
    return out


def must_hold_index(config, index, chain, partitions=()) -> list[str]:
    """The startup index: the domains that have must-holds, each with a few words on when it
    comes up and its must-holds' titles and ids. Critical ones show their one line instead,
    for models that cannot ask for a brief. Empty when the Brain has no must-holds."""
    notes = must_hold_notes(index, chain, partitions)
    if not notes:
        return []
    full = set(critical_ids(notes))
    domains: dict[str, dict] = {}
    for note in sorted(notes, key=lambda n: (n.id not in full, n.id)):
        for key, name in _domains(config, index, note):
            row = domains.setdefault(key, {"name": name, "notes": [], "hints": []})
            row["notes"].append(note)
            row["hints"] += [t for t in note.triggers if t not in row["hints"]]
    lines = ["## Must-hold domains", "", MUST_HOLD_INTRO, ""]
    for key in sorted(domains, key=lambda k: (k != "*", k)):
        row = domains[key]
        hints = row["hints"][:INDEX_HINTS]
        if not hints and key in config.areas:
            hints = [_one_line(config.areas[key].get("description") or "")]
        when = f" ({', '.join(h for h in hints if h)})" if any(hints) else ""
        shown = row["notes"][:INDEX_TITLES]
        entries = [f"{n.must_text.rstrip(' .') if n.id in full else n.title} (`{n.id}`)"
                   for n in shown]
        more = len(row["notes"]) - len(shown)
        if more:
            entries.append(f"and {more} more, which come with the brief")
        lines.append(f"- {row['name']}{when}: " + "; ".join(entries))
    lines.append("")
    return lines


def render(config, index, scopes, chain, partitions=(), tools=True) -> tuple[str, str]:
    """(kernel text without banner, fingerprint).

    Without `tools`, for a model that cannot call the brain at all (one side of a comparison):
    the same standing context with nothing it cannot do, so no Start contract, no list of
    skills to open and no working rule that needs a tool."""
    kernel_cfg = config.kernel
    approver = config.governance.get("approver") or config.owner
    lines = [f"# {config.name}", ""]
    if config.data.get("description"):
        lines += [str(config.data["description"]).strip(), ""]
    lines += [f"Scope: {' > '.join(chain)}. The closest scope wins.", ""]
    if tools:
        lines += [
            "## Start", "",
            "Call `get_task_context` first for every task, with the complete request and "
            "`startup_fingerprint: {fingerprint}`, and again for every later message that asks "
            "for something new; it sends only what the conversation does not hold. Reuse the "
            "`session_id` it returns on every later call in this conversation, and pass "
            "`fresh: true` after a context compaction. CLI "
            f"fallback: `{util.cli_name(config)} context \"<request>\"`.", "",
        ]
    lines += [
        "## Action policy", "",
        _one_line(kernel_cfg.get("action_policy") or ""), "",
    ]
    notes = standing_notes(index, chain, partitions)
    by_kind: dict[str, list] = {}
    for note in notes:
        if config.is_focus(note):
            continue
        by_kind.setdefault(note.kind, []).append(note)
    for kind in config.kind_order() + sorted(set(by_kind) - set(config.kinds)):
        members = by_kind.get(kind) or []
        if not members:
            continue
        heading = (config.kinds.get(kind) or {}).get("heading") or kind.title()
        lines += [f"## {heading}", ""]
        for note in members:
            text = note.startup_text or _one_line(note.body)
            lines.append(f"- `{note.id}`: {text}")
        lines.append("")
    if tools:
        lines += must_hold_index(config, index, chain, partitions)
    else:
        # A model that cannot call the brain gets each brief's must-holds in its packet; its
        # startup context carries the critical ones in full.
        musts = must_hold_notes(index, chain, partitions)
        critical = [n for n in musts if n.id in set(critical_ids(musts))]
        if critical:
            lines += ["## Must hold", ""]
            lines += [f"- `{n.id}`: {n.must_text}" for n in critical]
            lines.append("")
    skills_by_category: dict[str, list] = {}
    for skill in index.skills.values():
        if Scopes.admits(skill.scope, skill.partition, chain, partitions):
            skills_by_category.setdefault(skill.category or "other", []).append(skill.name)
    if skills_by_category and tools:
        lines += ["## Skills", "",
                  "Routed by the packet; open one with `get_skill` when you follow it.", ""]
        for category in sorted(skills_by_category):
            names = ", ".join(sorted(skills_by_category[category]))
            lines.append(f"- {category}: {names}")
        lines.append("")
    if not tools:
        lines += ["## Working with the brain", "", DISCLOSE]
    else:
        lines += [
            "## Working with the brain", "",
            "- The packet is the retrieval. If it lacks something the task needs, `search_notes` "
            "in your own words (then other words): it finds notes and the parts of filed "
            "documents. Open a note with `get_note`, a whole file with `get_reference`. Do not "
            "browse vault folders; open a procedure or reference document only when the packet "
            "points at it.",
            DISCLOSE,
            "- Capture as you go, without being asked: a durable rule, correction, preference, "
            "decision or changed fact the person states goes to `propose_note` (quote them in "
            "`evidence`); a reusable procedure you work out together goes to `propose_skill`; a "
            "document they share or are working on (a proposal, brief, plan or deck) goes to "
            "`add_file` with its `project`. One-off instructions need no capture. Each reply "
            f"says whether it applied at once or waits for {approver}.",
            "- Work that runs across conversations is a project (a Focus): start one with "
            "`create_focus`, with the names the person calls it, and record progress with "
            "`record_focus_update`. Never rewrite a Focus baseline.",
            "- When you save a file the person asked for in their outputs folder, call "
            "`record_output` with its path and your session_id, so they can see what it was "
            "made from.",
        ]
    for extra in kernel_cfg.get("extra") or []:
        lines.append(f"- {_one_line(extra)}")
    lines.append("")
    body = "\n".join(lines)
    fingerprint = util.short_hash(body.replace("{fingerprint}", ""), 12)
    return body.replace("{fingerprint}", fingerprint), fingerprint


def write_files(root: str, config, index, scopes, chain) -> dict:
    """Write CLAUDE.md and AGENTS.md (or the configured files) at the repository root."""
    text, fingerprint = render(config, index, scopes, chain)
    vault_rel = os.path.relpath(config.vault, root).replace("\\", "/")
    full = BANNER.format(vault=vault_rel, fingerprint=fingerprint,
                         cli=util.cli_name(config)) + "\n\n" + text
    written = []
    for name in config.kernel.get("files") or ["CLAUDE.md", "AGENTS.md"]:
        path = os.path.join(root, name)
        current = util.read_text(path) if os.path.isfile(path) else None
        if current != full:
            util.atomic_write(path, full)
            written.append(name)
    return {"fingerprint": fingerprint, "written": written, "tokens": util.tokens(full)}


def file_fingerprint(root: str, name="CLAUDE.md") -> str | None:
    path = os.path.join(root, name)
    if not os.path.isfile(path):
        return None
    match = re.search(r"kernel-fingerprint: ([0-9a-f]+)", util.read_text(path)[:400])
    return match.group(1) if match else None
